# -*- coding: utf-8 -*-
"""platform/role_catalog：**职业（职位）表** —— 一处真相，可扩展，可随任务走。

**起因**（老板 2026-10-11）：「职业列表落后了」

DSH 核实：这句话写死了四个职业（`routers/workshops_assign.py`）——
    「职业从 **组长/码农/画师/搜索者** 里选（按任务需要）」
⇒ 平台**选不出**产品/测试/运维/数据这类角色；做非"写代码画图"的项目时明显不够用。
而且它出现在**给 AI 的提示词**里 ⇒ AI 会照着这四个硬套，用户看到的就是"落后的列表"。

**本模块的设计取向（避免"再写死一张更大的表"）**
1. 给**一组推荐职业**（覆盖面比原来宽），但**不封闭**：提示词明确允许 AI
   **按任务需要新造职业**（新造的要能被用户看懂）；
2. 分组给出（管理/工程/设计/内容/数据/检索），方便界面按需展示；
3. **一处真相**：提示词、界面候选、（将来的）注册引导都从 `list_roles()` 取
   —— 与 `bridge_catalog` 同一纪律（规则 20：整体同步更新）。

⚠️ 角色是**自由文本**（`WorkshopMember.role` 就是字符串）⇒ 本模块只提供**推荐与约束**，
   不做枚举校验（不挡用户自己填）。
"""
from __future__ import annotations

#: 推荐职业表：`key` 仅用于分组展示；`role` 是真实写进成员的字符串
ROLES: list = [
    # ── 管理 ──
    {"role": "组长", "group": "管理", "note": "必须有：设计/分配/检查/纠错，不被员工隔间框住"},
    # ── 工程 ──
    {"role": "码农", "group": "工程", "note": "通用实现（前后端都行时用这个）"},
    {"role": "前端", "group": "工程", "note": "界面/交互"},
    {"role": "后端", "group": "工程", "note": "服务/接口/数据"},
    {"role": "测试", "group": "工程", "note": "验证与回归"},
    {"role": "运维", "group": "工程", "note": "部署/环境/看护"},
    # ── 设计与内容 ──
    {"role": "产品", "group": "产品", "note": "需求与验收标准"},
    {"role": "设计", "group": "设计", "note": "视觉/交互设计"},
    {"role": "美术", "group": "设计", "note": "图形/素材（原表叫「画师」）"},
    {"role": "文案", "group": "内容", "note": "文字/说明/对外材料"},
    # ── 数据与检索 ──
    {"role": "数据", "group": "数据", "note": "数据整理与分析"},
    {"role": "搜索者", "group": "检索", "note": "资料检索与核实"},
]

#: 必须有且只有一个的角色（平台流程依赖它）
REQUIRED_ROLE = "组长"

#: 老名字 → 新名字（兼容用户/历史里用的旧叫法；**只做展示提示，不改数据**）
LEGACY_ALIASES = {"画师": "美术"}


def list_roles() -> list:
    """推荐职业表（给界面候选、给提示词、给文档 —— 同一处真相）。"""
    return [dict(r) for r in ROLES]


def groups() -> dict:
    """按组归类（界面可分组展示）。"""
    out: dict = {}
    for r in ROLES:
        out.setdefault(r["group"], []).append(r["role"])
    return out


def role_names() -> list:
    return [r["role"] for r in ROLES]


def prompt_rules() -> str:
    """**给 AI 的规则**（选成员时用）。

    要点（与旧口径的差别）：
      · 不再把职业**封闭**在四个里；
      · 要求**贴合任务**，并允许按需要新造职业；
      · 旧叫法给个对应（画师→美术），避免同一件事两个名字。
    """
    names = "、".join(role_names())
    alias = "、".join("%s→%s" % (k, v) for k, v in LEGACY_ALIASES.items()) or "（无）"
    return (
        "规则：**%s必须有**（负责设计/分配/检查/纠错）；"
        "其余职业**按任务需要来定**，可参考这些常用职业：%s。"
        "若任务需要上面没有的职业，**可以按任务自行命名**（名字要让用户一眼看懂，如「语音处理」「合规审查」）；"
        "旧叫法对应：%s。"
        "display_name 与 harness_ids 一律用**已注册 harness 的完整名**；"
        "**没有合适 harness 的职业就不要填**（宁缺勿滥，别硬凑）。"
        % (REQUIRED_ROLE, names, alias)
    )
