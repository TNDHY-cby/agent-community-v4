class TestHeaderExtraction:
    def test_header_name_constant(self):
        assert ident.AGENT_TOKEN_HEADER == "x-agent-token"

    def test_extracts_lowercase(self):
        assert ident.extract_token_from_headers({"x-agent-token": "abc"}) == "abc"

    def test_case_insensitive_via_fastapi_headers(self):
        """真实调用方传的是 FastAPI Headers（大小写不敏感）。"""
        assert ident.extract_token_from_headers(
            Headers({"X-Agent-Token": "abc"})) == "abc"

    def test_missing_returns_empty(self):
        assert ident.extract_token_from_headers({}) == ""
        assert ident.extract_token_from_headers(Headers({})) == ""

    def test_strips_whitespace(self):
        assert ident.extract_token_from_headers({"x-agent-token": "  abc  "}) == "abc"


class TestHasAgentToken:
    def test_false_for_empty(self):
        assert ident.has_agent_token({}) is False
        assert ident.has_agent_token(None) is False

    def test_true_when_present(self):
        assert ident.has_agent_token({"agent_token": "x"}) is True

    def test_blank_token_is_false(self):
        """空串等于没签发 —— 否则会要求一个永远给不出的凭证。"""
        assert ident.has_agent_token({"agent_token": ""}) is False


