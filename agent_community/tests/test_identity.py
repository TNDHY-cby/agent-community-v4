class TestCheckRequestToken:
    def test_no_harness_id_passes(self, fake_config):
        assert ident.check_request_token("", {"agent_token": "x"}, {}) is None

    def test_legacy_harness_without_token_passes(self, fake_config):
        """向后兼容红线：未签发 token 的存量 harness 一律放行。"""
        assert ident.check_request_token("h-legacy", {}, {}) is None
        assert ident.check_request_token("h-legacy", None, {}) is None

    def test_missing_header_is_401(self, fake_config):
        ident.issue_agent_token("h1")
        verdict = ident.check_request_token(
            "h1", {"agent_token": "issued"}, Headers({}))
        assert verdict is not None
        assert verdict[0] == 401, "缺凭证应与校验失败区分（401）"
        assert "x-agent-token" in verdict[1]

    def test_wrong_token_is_403(self, fake_config):
        ident.issue_agent_token("h1")
        verdict = ident.check_request_token(
            "h1", {"agent_token": "issued"}, Headers({"X-Agent-Token": "0" * 64}))
        assert verdict is not None
        assert verdict[0] == 403, "凭证错误应为 403"

    def test_correct_token_passes(self, fake_config):
        tok = ident.issue_agent_token("h1")
        assert ident.check_request_token(
            "h1", {"agent_token": "issued"}, Headers({"X-Agent-Token": tok})) is None

    def test_uses_constant_time_compare(self):
        """防时序侧信道：必须走 hmac.compare_digest，不得是裸 `==`。"""
        import inspect

        src = inspect.getsource(ident.verify_agent_token)
        assert "compare_digest" in src, (
            "verify_agent_token 必须使用 hmac.compare_digest（常数时间），"
            "退化成正则/== 比较会引入时序侧信道"
        )
