class TestVerify:
    def test_correct_token_accepted(self, fake_config):
        tok = ident.issue_agent_token("harness-A")
        assert ident.verify_agent_token("harness-A", tok) is True

    def test_wrong_token_rejected(self, fake_config):
        ident.issue_agent_token("harness-A")
        assert ident.verify_agent_token("harness-A", "0" * 64) is False

    def test_token_bound_to_harness_id(self, fake_config):
        """拿 A 的 token 冒充 B 必须失败 —— token 是与 harness_id 绑定的。"""
        tok_a = ident.issue_agent_token("harness-A")
        assert ident.verify_agent_token("harness-B", tok_a) is False

    def test_empty_token_rejected(self, fake_config):
        assert ident.verify_agent_token("harness-A", "") is False
        assert ident.verify_agent_token("harness-A", None) is False

    def test_tampered_token_rejected(self, fake_config):
        tok = ident.issue_agent_token("harness-A")
        tampered = ("b" if tok[0] != "b" else "c") + tok[1:]
        assert ident.verify_agent_token("harness-A", tampered) is False


